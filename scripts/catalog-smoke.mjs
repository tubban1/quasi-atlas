import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const base=process.env.QUASI_URL||'http://127.0.0.1:5188/';
let browser;try{browser=await chromium.launch({channel:'chrome',headless:true});}catch{browser=await chromium.launch({headless:true});}
const errors=[],checks=[];
const monitor=page=>page.on('pageerror',e=>errors.push(String(e)));
try{
  const page=await browser.newPage({viewport:{width:1440,height:900}});monitor(page);
  await page.goto(base+'?screen=catalog',{waitUntil:'domcontentloaded'});
  await page.locator('#homeTopicGrid .topic-card').first().waitFor({state:'attached'});
  assert.equal(await page.locator('#catalogScreen').isVisible(),true);
  assert.equal(await page.locator('.catalog-group').count(),5);
  assert.ok(await page.locator('.catalog-card').count()>=20);
  checks.push('catalog deep link and five searchable feature categories');
  await page.locator('#catalogSearch').fill('H0');
  assert.equal(await page.locator('.catalog-card').count(),1);
  await page.locator('.catalog-card[data-feature=h0]').click();
  assert.equal(await page.locator('#studioScreen').isVisible(),true);
  assert.equal(await page.locator('#focusResearch').isVisible(),true);
  assert.equal(await page.locator('#h0Panel').getAttribute('open'),'');
  checks.push('H0 search -> interactive research experiment');
  await page.locator('.more-nav summary').click();
 await page.locator('.nav-link[data-screen=catalog]').click();
  await page.locator('#catalogSearch').fill('六题');
  await page.locator('.catalog-card[data-feature=transfer]').click();
  assert.equal(await page.locator('#transferCheck').getAttribute('open'),'');
  checks.push('G6 six-question self check can be located and opened');
  await page.locator('.more-nav summary').click();
 await page.locator('.nav-link[data-screen=catalog]').click();
  await page.locator('#catalogSearch').fill('Notebook');
  await page.locator('.catalog-card[data-feature=notebook]').click();
  assert.equal(await page.locator('#notebookDialog').isVisible(),true);
  await page.locator('#nbClose').click();
  checks.push('G2 Notebook reachable');
  await page.locator('.more-nav summary').click();
 await page.locator('.nav-link[data-screen=catalog]').click();
  await page.locator('#catalogSearch').fill('G5');
  await page.locator('.catalog-card[data-feature=g5]').click();
  assert.equal(await page.locator('#roadmapScreen').isVisible(),true);
  assert.equal(await page.locator('[data-milestone=G5]').getAttribute('open'),'');
  assert.ok(page.url().includes('milestone=G5'));
  checks.push('research prototype links to transparent roadmap milestone');
  await page.goto(base+'?screen=roadmap&milestone=G4');
  await page.locator('#homeTopicGrid .topic-card').first().waitFor({state:'attached'});
  assert.equal(await page.locator('[data-milestone=G4]').getAttribute('open'),'');
  checks.push('research milestone deep link');
  await page.goto(base);
  await page.locator('#homeTopicGrid .topic-card').first().waitFor({state:'attached'});
  await page.keyboard.press('/');
  assert.equal(await page.locator('#catalogScreen').isVisible(),true);
  assert.equal(await page.evaluate(()=>document.activeElement.id),'catalogSearch');
  checks.push('slash keyboard shortcut');
  await page.locator('#catalogSearch').fill('');
  await page.screenshot({path:'docs/ui-catalog-desktop.png',fullPage:true,animations:'disabled'});
  const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});monitor(mobile);
  await mobile.goto(base+'?screen=catalog',{waitUntil:'domcontentloaded'});
  await mobile.locator('#homeTopicGrid .topic-card').first().waitFor({state:'attached'});
  assert.equal(await mobile.locator('#catalogScreen').isVisible(),true);
  const sizes=await mobile.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth,nav:document.querySelector('.global-nav').getBoundingClientRect().right}));
  assert.ok(sizes.scroll<=sizes.client+2,JSON.stringify(sizes));
  await mobile.locator('#catalogFilters [data-filter=learn]').click();
  assert.equal(await mobile.locator('.catalog-card').count(),6);
  await mobile.locator('.catalog-card[data-feature=lesson-beats]').click();
  assert.equal(await mobile.locator('#studioScreen').isVisible(),true);
  assert.equal(await mobile.locator('#lifeLab').isVisible(),true);
  await mobile.locator('.more-nav summary').click();
 await mobile.locator('.nav-link[data-screen=catalog]').click();
  await mobile.screenshot({path:'docs/ui-catalog-mobile.png',fullPage:true,animations:'disabled'});
  checks.push('390px mobile without overflow; filters and lessons');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({checks,mobile:sizes,pageErrors:errors},null,2));
}finally{await browser.close();}
