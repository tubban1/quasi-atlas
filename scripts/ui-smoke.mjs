import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const url=process.env.QUASI_URL||'http://127.0.0.1:5188/';
let browser;
try{browser=await chromium.launch({channel:'chrome',headless:true});}catch{browser=await chromium.launch({headless:true});}
const errors=[],report={url,screens:[],mobile:{},invalidLinks:0};
try{
 const desktop=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
 desktop.on('pageerror',e=>errors.push('desktop '+String(e)));
 desktop.on('console',m=>{if(m.type()==='error')errors.push('desktop console '+m.text());});
 await desktop.goto(url,{waitUntil:'domcontentloaded'});
 await desktop.locator('#homeTopicGrid .topic-card').first().waitFor();
 assert.equal(await desktop.locator('.topic-card').count(),6,'six home cards');
 assert.equal(await desktop.locator('#homeScreen').isVisible(),true,'home first');
 assert.equal(await desktop.locator('#studioScreen').isVisible(),false,'studio closed');
 await desktop.screenshot({path:'docs/ui-home-desktop.png',fullPage:true,animations:'disabled'});
 report.screens.push('home');
 await desktop.locator('.nav-link[data-screen="roadmap"]').click();
 assert.equal(await desktop.locator('#roadmapScreen').isVisible(),true);
 assert.equal(await desktop.locator('#roadmapTimeline .milestone').count(),7,'G0–G6 timeline');
 assert.equal(await desktop.locator('.milestone-done').count(),1);
 assert.equal(await desktop.locator('.milestone-progress').count(),3);
 assert.equal(await desktop.locator('.milestone-planned').count(),3);
 await desktop.locator('#roadmapTimeline .milestone').last().locator('summary').click();
 await desktop.screenshot({path:'docs/ui-roadmap-desktop.png',fullPage:true,animations:'disabled'});
 report.screens.push('roadmap');
 await desktop.locator('.nav-link[data-screen="home"]').click();
 await desktop.locator('.topic-card[data-launch="puddles"]').click();
 assert.equal(await desktop.locator('#studioScreen').isVisible(),true);
 assert.equal(await desktop.locator('#lifeTitle').textContent(),'雨后水坑为什么连在一起？');
 await desktop.waitForFunction(()=>document.querySelector('#numericStatus')?.textContent==='计算完成',{timeout:15000});
 await desktop.screenshot({path:'docs/ui-studio-desktop.png',fullPage:true,animations:'disabled'});
 report.screens.push('studio');
 await desktop.locator('.mode[data-mode="research"]').click();
 assert.equal(await desktop.locator('.mode[data-mode="research"]').getAttribute('aria-selected'),'true');
 await desktop.locator('#findCritical').click();
 await desktop.waitForFunction(()=>!document.querySelector('#findCritical').disabled,{timeout:25000});
 report.screens.push('research');
 await desktop.locator('.nav-link[data-screen="home"]').click();
 assert.equal(await desktop.locator('#homeScreen').isVisible(),true);
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});
 mobile.on('pageerror',e=>errors.push('mobile '+String(e)));
 mobile.on('console',m=>{if(m.type()==='error')errors.push('mobile console '+m.text());});
 await mobile.goto(url,{waitUntil:'domcontentloaded'});
 await mobile.locator('.topic-card').first().waitFor();
 await mobile.screenshot({path:'docs/ui-home-mobile.png',fullPage:true,animations:'disabled'});
 report.mobile.homeWidth=await mobile.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
 assert.ok(report.mobile.homeWidth.scroll<=report.mobile.homeWidth.client+2,'mobile home has no horizontal scroll');
 await mobile.locator('.topic-card[data-launch="weather"]').click();
 assert.equal(await mobile.locator('#studioScreen').isVisible(),true);
 await mobile.locator('#lifeSlider').waitFor();
 await mobile.waitForFunction(()=>document.querySelector('#numericStatus')?.textContent==='计算完成',{timeout:15000});
 await mobile.screenshot({path:'docs/ui-studio-mobile.png',fullPage:true,animations:'disabled'});
 report.mobile.studioWidth=await mobile.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
 assert.ok(report.mobile.studioWidth.scroll<=report.mobile.studioWidth.client+2,'mobile studio has no horizontal scroll');
 await mobile.locator('.nav-link[data-screen="roadmap"]').click();
 await mobile.screenshot({path:'docs/ui-roadmap-mobile.png',fullPage:true,animations:'disabled'});
 report.mobile.roadmapWidth=await mobile.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
 assert.ok(report.mobile.roadmapWidth.scroll<=report.mobile.roadmapWidth.client+2,'mobile roadmap has no horizontal scroll');
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({...report,pageErrors:errors},null,2));
}finally{await browser.close();}
