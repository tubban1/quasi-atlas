import {chromium} from 'playwright';
import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
let browser;try{browser=await chromium.launch({channel:'chrome',headless:true});}catch{browser=await chromium.launch({headless:true});}
const url=process.env.QUASI_URL||'http://127.0.0.1:5188/';
const errors=[],out={url,desktop:[],mobile:'pending'};
try{
 const p=await browser.newPage({viewport:{width:1440,height:900},acceptDownloads:true});
 p.on('pageerror',e=>errors.push(e.message));p.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 await p.goto(url,{waitUntil:'domcontentloaded'});
 await p.locator('.topic-card[data-launch="mountain"]').click();
 await p.waitForFunction(()=>document.querySelector('#numericStatus')?.textContent==='计算完成',{timeout:15000});
 await p.locator('.mode[data-mode="research"]').click();
 assert.equal(await p.locator('#h0Panel').getAttribute('open'),null,'collapsed by default');
 await p.locator('#h0Panel summary').click();
 await p.locator('#h0Direction').selectOption('superlevel');
 await p.locator('#runH0').click();
 await p.waitForFunction(()=>document.querySelector('#h0Audit')?.dataset.status==='MATCH',{timeout:20000});
 assert.ok(Number(await p.locator('#h0Overview strong').textContent())>=0);
 assert.ok(await p.locator('.h0-bar-row').count()>0);
 assert.match(await p.locator('#h0Limits').textContent(),/H1 尚未计算/);
 out.desktop.push('superlevel H0 vs independent flood MATCH');
 await p.locator('#h0Direction').selectOption('sublevel');
 assert.equal(await p.locator('#h0Freshness').getAttribute('data-stale'),'true');
 assert.equal(await p.locator('#exportH0').isDisabled(),true);
 await p.locator('#runH0').click();
 await p.waitForFunction(()=>document.querySelector('#h0Audit')?.dataset.status==='MATCH'&&document.querySelector('#h0Freshness')?.dataset.stale==='false',{timeout:20000});
 out.desktop.push('sublevel H0 MATCH with stale direction guard');
 const filePromise=p.waitForEvent('download',{timeout:15000});
 await p.locator('#exportH0').click();const f=await filePromise;
 const data=JSON.parse(await readFile(await f.path(),'utf8'));
 assert.equal(data.schema,'quasi-atlas.h0-audit/1.0');
 assert.equal(data.reference.status,'MATCH');
 assert.equal(data.persistence.evidence,'E1');assert.equal(data.persistence.certified,false);
 assert.equal(data.source.id,'archipelago');
 out.desktop.push('research JSON E1 export');
 await p.locator('#levelSlider').evaluate(e=>{e.value=String(Math.min(Number(e.max),Number(e.value)+.55));e.dispatchEvent(new Event('input',{bubbles:true}));});
 await p.waitForFunction(()=>document.querySelector('#h0Freshness')?.dataset.stale==='true',{timeout:10000});
 assert.equal(await p.locator('#exportH0').isDisabled(),true);
 out.desktop.push('parameter-change invalidates H0 export');
 await p.screenshot({path:'docs/g3-h0-desktop.png',animations:'disabled'});
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 mobile.on('pageerror',e=>errors.push('mobile '+e.message));
 await mobile.goto(url,{waitUntil:'domcontentloaded'});
 await mobile.locator('.topic-card[data-launch="puddles"]').click();
 await mobile.locator('.mode[data-mode="research"]').click();
 await mobile.locator('#h0Panel summary').click();
 await mobile.locator('#runH0').click();
 await mobile.waitForFunction(()=>document.querySelector('#h0Audit')?.dataset.status==='MATCH',{timeout:20000});
 const dims=await mobile.evaluate(()=>({scroll:document.documentElement.scrollWidth,viewport:document.documentElement.clientWidth}));
 assert.ok(dims.scroll<=dims.viewport+2,JSON.stringify(dims));
 await mobile.screenshot({path:'docs/g3-h0-mobile.png',animations:'disabled',fullPage:true});
 out.mobile='PASS, no horizontal overflow';assert.deepEqual(errors,[]);
 console.log(JSON.stringify({...out,errors},null,2));
}finally{await browser.close();}
