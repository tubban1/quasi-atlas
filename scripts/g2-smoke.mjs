import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
const url=process.env.QUASI_URL||'http://127.0.0.1:5188/';
let browser;try{browser=await chromium.launch({channel:'chrome',headless:true});}catch{browser=await chromium.launch({headless:true});}
const failures=[],record={url,steps:[],mobile:'pending'};
async function ready(p){await p.waitForFunction(()=>document.querySelector('#numericStatus')?.textContent==='计算完成',{timeout:25000});}
const watch=p=>{p.on('pageerror',e=>failures.push(String(e)));p.on('console',m=>{if(m.type()==='error')failures.push(m.text());});};
try{
 const page=await browser.newPage({viewport:{width:1440,height:900},acceptDownloads:true});watch(page);
 await page.goto(url,{waitUntil:'domcontentloaded'});
 await page.locator('.topic-card[data-launch="mountain"]').click();await ready(page);
 assert.equal(await page.locator('#openNotebook').isVisible(),true);
 await page.locator('#openNotebook').click();
 assert.equal(await page.locator('#notebookDialog').isVisible(),true);
 await page.locator('#nbQuestion').fill('山地等值线什么时候合并？');
 await page.locator('#nbHypothesis').fill('假设海拔提高，连通区域减少');
 await page.locator('#nbObservation').fill('观察当前有限窗口');
 await page.locator('#nbCounterexample').fill('缩小采样网格可能丢失细节');
 await page.locator('#nbConclusion').fill('仍为 E1 数值观察');
 await page.locator('#nbLabel').fill('实验 A');
 await page.locator('#nbCapture').click();
 await page.waitForFunction(()=>document.querySelector('#nbCount')?.textContent==='1',{timeout:15000});
 assert.ok((await page.locator('#nbList').textContent()).includes('实验 A'));
 record.steps.push('capture-A');
 await page.locator('#nbClose').click();
 await page.locator('#levelSlider').evaluate(el=>{el.value=String(Math.min(Number(el.max),Number(el.value)+.65));el.dispatchEvent(new Event('input',{bubbles:true}));});
 await ready(page);
 await page.locator('#openNotebook').click();
 assert.equal(await page.locator('#nbStale').getAttribute('data-stale'),'true','stale after changing numerical input');
 await page.locator('#nbLabel').fill('实验 B');
 await page.locator('#nbCapture').click();
 await page.waitForFunction(()=>document.querySelector('#nbCount')?.textContent==='2',{timeout:15000});
 record.steps.push('capture-B-stale');
 await page.screenshot({path:'docs/g2-notebook-desktop.png',animations:'disabled'});
 await page.locator('#nbCompareA').selectOption('0');
 await page.locator('#nbCompareB').selectOption('1');
 await page.locator('#nbCompare').click();
 assert.ok((await page.locator('#nbComparison').textContent()).includes('差值'));
 record.steps.push('compare');
 await page.locator('#nbReplay').click();
 await page.waitForFunction(()=>/MATCH|DIFFERENT|INVALID/.test(document.querySelector('#nbReplayOutput')?.dataset.status||''),{timeout:25000});
 assert.equal(await page.locator('#nbReplayOutput').getAttribute('data-status'),'MATCH');
 record.steps.push('browser-worker-replay-MATCH');
 const dlPromise=page.waitForEvent('download',{timeout:15000});
 await page.locator('#nbExportJSON').click();const downloaded=await dlPromise;
 const path=await downloaded.path(),notebook=JSON.parse(await readFile(path,'utf8'));
 assert.equal(notebook.schema,'quasi-atlas.notebook/1.1');
 assert.match(notebook.buildProvenance.mathSourceSha256,/^sha256:[a-f0-9]{64}$/);
 assert.match(notebook.buildProvenance.lockSha256,/^sha256:[a-f0-9]{64}$/);
 assert.equal(notebook.snapshots.length,2);
 const cli=spawnSync(process.execPath,['scripts/replay-notebook.mjs',path],{encoding:'utf8',timeout:30000});
 assert.equal(cli.status,0,'CLI '+cli.stderr);const report=JSON.parse(cli.stdout);
 assert.equal(report.status,'MATCH');assert.equal(report.results.length,2);
 record.steps.push('export-and-headless-replay-MATCH');
 const csvDownload=page.waitForEvent('download');
 await page.locator('#nbExportCSV').click();const csvFile=await csvDownload;
 const csv=await readFile(await csvFile.path(),'utf8');
 assert.ok(csv.includes('snapshot_hash'));assert.ok(csv.includes('实验 B'));record.steps.push('CSV');
 await page.locator('#nbClose').click();
 await page.reload();await page.locator('.nav-link[data-screen="studio"]').click();await ready(page);
 assert.equal(await page.locator('#nbCount').textContent(),'2','local-first persistence across reload');
 record.steps.push('local-persistence');
 await page.locator('#openNotebook').click();
 await page.locator('#nbImport').setInputFiles({name:'untrusted.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({...notebook,title:'modified without hash'}))});
 await page.waitForFunction(()=>document.querySelector('#nbStatus')?.textContent.includes('拒绝导入'),{timeout:15000});
 assert.equal(await page.locator('#nbCount').textContent(),'2');
 record.steps.push('reject-tampered-import');
 const old={project:'Quasi Atlas',version:'0.1',scientific:notebook.snapshots[0].scientific};
 page.once('dialog',d=>d.accept());
 await page.locator('#nbImport').setInputFiles({name:'g0-legacy.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(old))});
 await page.waitForFunction(()=>document.querySelector('#nbCount')?.textContent==='1',{timeout:15000});
 record.steps.push('verified-G0-migration');
 await page.locator('#nbReplay').click();
 await page.waitForFunction(()=>document.querySelector('#nbReplayOutput')?.dataset.status==='MATCH',{timeout:25000});
 page.once('dialog',d=>d.accept());
 await page.locator('#nbImport').setInputFiles({name:'notebook.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(notebook))});
 await page.waitForFunction(()=>document.querySelector('#nbCount')?.textContent==='2',{timeout:15000});
 record.steps.push('G2-roundtrip-import');
 await page.locator('#nbClose').click();
 await page.locator('#openNotebook').click();
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});watch(mobile);
 await mobile.goto(url,{waitUntil:'domcontentloaded'});
 await mobile.locator('.topic-card[data-launch="weather"]').click();await ready(mobile);
 assert.equal(await mobile.locator('#openNotebook').isVisible(),true);
 await mobile.locator('#openNotebook').click();
 assert.equal(await mobile.locator('#notebookDialog').isVisible(),true);
 const measure=await mobile.evaluate(()=>({viewport:innerWidth,width:document.documentElement.scrollWidth,dialog:document.querySelector('#notebookDialog').getBoundingClientRect().width}));
 assert.ok(measure.width<=measure.viewport+2,JSON.stringify(measure));
 await mobile.screenshot({path:'docs/g2-notebook-mobile.png',animations:'disabled'});
 await mobile.locator('#nbClose').click();record.mobile='pass';
 assert.deepEqual(failures,[]);
 console.log(JSON.stringify({...record,jsErrors:failures},null,2));
}finally{await browser.close();}
